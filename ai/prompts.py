# ============== 投研框架化约束（专业性增强） ==============
RESEARCH_FRAMEWORK = """\n\n【投研框架约束】请严格遵循：
1. 先给结论，再分维度展开；维度固定为：财务质量、估值水平、风险提示、近期催化、综合结论。
2. 每个判断必须引用具体数字（营收/净利/PE/PB/ROE/涨跌幅等），禁止出现「经营良好」类空话。
3. 严格区分「事实」（来自上方数据）与「推测/观点」。
4. 所有数字须与上方数据一致；数据不足时明确说明缺口，不得编造。
5. 来源为知识库/公告/研报时，正文用方括号编号 [1][2] 标注，文末附「## 参考资料」。"""

STRUCTURED_CONTRACT = """\n\n【输出契约】正文结束后，必须新增一个二级标题小节「## 评分与置信度」，内容形如：
- 综合评分（0-100）：<数字>，依据：<一句话>
- 置信度（0-1）：<数字>，依据：<数据覆盖度与分歧度说明>"""

# spec §6.5 合规免责声明（在最外层统一注入一次）
DISCLAIMER_SEC65 = (
    "本内容为 AI 基于公开数据的投研观点整理，仅供参考，不构成任何投资建议，"
    "不承诺收益，投资有风险。"
)


def with_framework(prompt: str) -> str:
    """给单类型分析 prompt 追加投研框架约束与结构化输出契约。"""
    return prompt + RESEARCH_FRAMEWORK + STRUCTURED_CONTRACT

